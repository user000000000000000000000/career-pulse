const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const assert = require('node:assert/strict')
const base = 'http://127.0.0.1:5174/career-pulse/'
;(async () => {
  const browser = await chromium.launch({ channel: 'chrome', headless: true })
  try {
    const page = await browser.newPage()
    const errors = []
    page.on('pageerror', e => errors.push(e.message))
    const settle = async () => {
      await page.locator('.site-header nav').waitFor()
      await page.waitForTimeout(700)
    }
    const y = () => page.evaluate(() => window.scrollY)
    const scroll = async top => {
      await page.evaluate(top => window.scrollTo({ top, behavior: 'instant' }), top)
      await page.waitForTimeout(400)
    }
    const top = async label => {
      await settle()
      assert.equal(await y(), 0, label)
      await page.waitForTimeout(800)
      assert.equal(await y(), 0, label + ' after image/font loading')
      console.log(label, 'scrollY =', await y())
    }
    await page.goto(base)
    await top('First visit')
    assert.equal(await page.locator('.bird-helper').isVisible(), false)
    await scroll(1800)
    await page.reload()
    await top('Normal reload from 1800')
    const cdp = await page.context().newCDPSession(page)
    await scroll(1500)
    await cdp.send('Page.reload', { ignoreCache: true })
    await page.waitForEvent('load')
    await top('Hard reload from 1500')
    await page.locator('.site-header').getByRole('link', { name: 'Диагностика', exact: true }).click()
    await settle()
    assert.ok(await y() > 300, 'Anchor still works')
    await page.reload()
    await top('Reload after #how navigation')
    await scroll(380)
    assert.equal(await page.locator('.bird-helper').isVisible(), true)
    assert.ok(await page.locator('.site-header nav').evaluate(el => el.getBoundingClientRect().top >= 0), 'Header stays on screen while scrolled')
    await page.waitForTimeout(800)
    assert.equal(await y(), 380, 'Ordinary scrolling is not reset')
    await scroll(0)
    assert.equal(await page.locator('.bird-helper').isVisible(), false)
    assert.ok(await page.locator('.site-header nav').evaluate(el => el.getBoundingClientRect().top >= 0))
    await scroll(1200)
    await page.locator('.site-header').getByRole('link', { name: 'Материалы', exact: true }).click()
    await page.waitForURL(base + 'professions')
    await top('New route')
    await page.locator('.cat-card').first().waitFor()
    await scroll(600)
    await page.goBack()
    await settle()
    assert.ok(Math.abs(await y() - 1200) < 3, 'Back restores homepage')
    await page.goForward()
    await settle()
    assert.ok(Math.abs(await y() - 600) < 3, 'Forward restores catalog')
    await page.goto(base + '#professions')
    await settle()
    assert.ok(await y() > 500, 'Direct anchor visit works')
    await page.reload()
    await top('Reload direct anchor')
    for (const hash of ['how', 'about']) {
      await page.goto(base + '#' + hash)
      await settle()
      assert.ok(await y() > 300, 'Direct #' + hash + ' visit works')
      await page.reload()
      await top('Reload #' + hash)
    }
    await page.setViewportSize({ width: 390, height: 844 })
    await scroll(1500)
    await page.reload()
    await top('Mobile reload')
    await scroll(380)
    assert.equal(await page.locator('.bird-helper').isVisible(), true)
    await scroll(0)
    assert.equal(await page.locator('.bird-helper').isVisible(), false)
    assert.deepEqual(errors, [])
    console.log('PASS: Chrome reloads, anchors, history, helper, desktop/mobile; no page errors')
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })
