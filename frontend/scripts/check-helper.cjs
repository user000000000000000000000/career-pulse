const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const assert = require('node:assert/strict')
const base = 'http://127.0.0.1:5174/career-pulse/'
;(async () => {
  const browser = await chromium.launch({ channel: 'chrome', headless: true })
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
    const errors = []
    page.on('pageerror', e => errors.push(e.message))
    await page.clock.install()
    const scroll = async top => {
      await page.evaluate(top => scrollTo({ top, behavior: 'instant' }), top)
      await page.waitForTimeout(150)
      await page.clock.runFor(400)
      await page.waitForTimeout(400)
    }
    await page.goto(base)
    await page.locator('.bird-helper').waitFor({ state: 'attached' })
    await page.locator('.lv-hero').waitFor()
    await page.clock.runFor(1000)
    assert.equal(await page.locator('.bird-helper').isVisible(), false)
    await scroll(380)
    assert.equal(await page.locator('.bird-helper').isVisible(), true)
    assert.equal(await page.locator('.bird-helper__flight').evaluate(el => getComputedStyle(el).animationName), 'bird-helper-flight')
    await page.clock.fastForward(16000)
    assert.equal(await page.locator('#bird-helper-tip').count(), 0, 'No immediate automatic popup')
    await page.clock.fastForward(2200)
    assert.equal(await page.locator('#bird-helper-tip').count(), 1, 'First automatic hint')
    await page.clock.fastForward(7100)
    assert.equal(await page.locator('#bird-helper-tip').count(), 0, 'Automatic hint closes')
    await page.clock.fastForward(30000)
    assert.equal(await page.locator('#bird-helper-tip').count(), 0, 'No frequent messages')
    const tips = []
    for (let i = 0; i < 19; i++) {
      await page.locator('.bird-helper__toggle').click()
      assert.equal(await page.locator('.bird-helper__wing--greeting').count(), 2, 'Both real image wings greet on click')
      tips.push(await page.locator('#bird-helper-tip p').innerText())
      await page.getByRole('button', { name: 'Закрыть подсказку', exact: true }).click()
    }
    assert.equal(new Set(tips).size, 19, 'Shuffled bag does not repeat')
    await page.clock.fastForward(180000)
    assert.equal(await page.locator('#bird-helper-tip').count(), 0, 'Dismissal mutes automatic hints')
    await scroll(0)
    assert.equal(await page.locator('.bird-helper').isVisible(), false)
    await page.locator('.site-header').getByRole('link', { name: 'Материалы', exact: true }).click()
    await page.waitForURL(base + 'professions')
    await page.locator('.cat-card').first().waitFor()
    await scroll(380)
    await page.locator('.bird-helper__toggle').click()
    assert.match(await page.locator('#bird-helper-tip p').innerText(), /поиск|Сравни несколько профессий/)
    await page.clock.runFor(500)
    await page.screenshot({ path: 'design-preview/helper-desktop.png' })
    await page.getByRole('button', { name: 'Закрыть подсказку', exact: true }).click()
    await page.setViewportSize({ width: 390, height: 844 })
    await page.locator('.bird-helper__toggle').click()
    await page.clock.runFor(400)
    const box = await page.locator('#bird-helper-tip').boundingBox()
    assert.ok(box.x >= 0 && box.x + box.width <= 390)
    await page.screenshot({ path: 'design-preview/helper-mobile.png' })
    await page.keyboard.press('Escape')
    assert.equal(await page.locator('#bird-helper-tip').count(), 0)
    await page.emulateMedia({ reducedMotion: 'reduce' })
    assert.equal(await page.locator('.bird-helper__flight').evaluate(el => getComputedStyle(el).animationName), 'none')
    assert.deepEqual(await page.locator('.bird-helper__wing').evaluateAll(els => els.map(el => getComputedStyle(el).animationName)), ['none', 'none'])
    await page.getByRole('button', { name: 'Скрыть птичку-помощника до перезагрузки' }).click()
    assert.equal(await page.locator('.bird-helper').count(), 0)
    assert.deepEqual(errors, [])
    console.log('PASS: threshold, flying pose, both wing greetings, automatic timing, 19 unique manual hints, mute, contextual hint, mobile bubble, Escape, reduced motion, hide; no page errors')
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })
