const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const assert = require('node:assert/strict')
const base = 'http://127.0.0.1:5174/career-pulse/'
;(async () => {
  const browser = await chromium.launch({ channel: 'chrome', headless: true })
  try {
    const page = await browser.newPage()
    const errors = []
    page.on('pageerror', e => errors.push(e.message))
    for (const width of [1440, 1100, 820, 390, 320]) {
      await page.setViewportSize({ width, height: 1000 })
      await page.goto(base + 'dashboard')
      await page.locator('.dashboard-workspace h1').waitFor()
      await page.waitForTimeout(1000)
      assert.equal(await page.locator('.appnav-burger').count(), 0, 'No conflicting global menu')
      assert.equal(await page.locator('.dashboard-workspace .topbar').count(), 0)
      assert.equal(await page.locator('.welcome-banner').evaluate(el => getComputedStyle(el).backgroundImage), 'none')
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, 'Overflow at ' + width)
      const expectedName = await page.evaluate(() => {
        const parts = JSON.parse(localStorage.getItem('cp_user')).name.trim().split(/\s+/)
        return parts[1] || parts[0]
      })
      assert.ok((await page.locator('.wb-text h1').innerText()).includes(expectedName))
      assert.equal(await page.locator('.block-card').count(), 10)
      assert.equal(await page.locator('.axis-card').count(), 4)
      const titles = await page.evaluate(async () => {
        const { BLOCKS } = await import('/career-pulse/src/shared/config/blocks.js')
        return BLOCKS.map(b => b.title)
      })
      assert.deepEqual(await page.locator('.bc-title').allTextContents(), titles)
      const sidebar = page.locator('#dashboard-sidebar')
      const toggle = page.getByRole('button', { name: 'Меню кабинета', exact: true })
      assert.equal(await sidebar.isVisible(), width > 1100)
      await page.screenshot({ path: `design-preview/dashboard-layout-${width}.png` })
      await toggle.click()
      assert.equal(await sidebar.isVisible(), width <= 1100)
      if (width <= 1100) {
        assert.equal(await page.evaluate(() => document.body.style.overflow), 'hidden')
        await page.getByRole('button', { name: 'Меню пользователя', exact: true }).click()
        assert.ok(await page.getByRole('link', { name: 'Настройки профиля', exact: true }).isVisible())
        await page.waitForTimeout(400)
        await page.screenshot({ path: `design-preview/dashboard-menu-${width}.png` })
        await page.keyboard.press('Escape')
        assert.equal(await sidebar.isVisible(), false)
        assert.equal(await page.evaluate(() => document.body.style.overflow), '')
        await toggle.click()
        await sidebar.getByRole('link', { name: 'Профиль', exact: true }).click()
        await page.waitForURL(base + 'profile')
        assert.equal(await page.evaluate(() => document.body.style.overflow), '')
        await page.goto(base + 'dashboard')
        await page.locator('.dashboard-workspace h1').waitFor()
      } else {
        await toggle.click()
        await page.evaluate(() => scrollTo({ top: 1300, behavior: 'instant' }))
        await page.waitForTimeout(400)
        assert.ok(await sidebar.evaluate(el => el.getBoundingClientRect().top >= document.querySelector('.site-header nav').getBoundingClientRect().bottom))
      }
      await page.locator('.site-footer').scrollIntoViewIfNeeded()
      await page.waitForTimeout(500)
      if (width > 1100) assert.ok(await sidebar.evaluate(el => el.getBoundingClientRect().bottom <= document.querySelector('.dashboard-footer').getBoundingClientRect().top + 1), 'Sticky sidebar stops before footer')
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
      assert.ok(await page.locator('.site-footer .brand-mark--white').evaluate(img => img.complete && img.naturalWidth > 0))
      assert.equal(await page.locator('.site-footer #cookie-settings').count(), 1)
      await page.locator('.site-footer').screenshot({ path: `design-preview/dashboard-footer-${width}.png` })
      console.log('PASS', width, 'layout, real name, 10 tests, single menu, footer')
    }
    await page.setViewportSize({ width: 1440, height: 1000 })
    await page.goto(base + 'dashboard')
    await page.locator('.bc-btn--result').first().click()
    await page.locator('.brm-card').waitFor()
    await page.locator('.brm-close').click()
    await page.locator('.btn-tour').click()
    await page.locator('.modal-overlay.show .modal-close').click()
    await page.getByRole('button', { name: 'Записаться', exact: true }).click()
    const storedName = await page.evaluate(() => JSON.parse(localStorage.getItem('cp_user')).name)
    assert.equal(await page.getByPlaceholder('Как к тебе обращаться').inputValue(), storedName)
    await page.locator('.modal-overlay.show .modal-close').click()
    await page.locator('#cookie-settings').click()
    await page.getByRole('button', { name: 'Понятно', exact: true }).click()
    await page.getByRole('button', { name: 'Меню пользователя', exact: true }).click()
    await page.getByRole('link', { name: 'Выйти из кабинета', exact: true }).click()
    await page.getByRole('button', { name: 'Отмена', exact: true }).click()
    assert.equal(new URL(page.url()).pathname, '/career-pulse/dashboard')
    await page.evaluate(() => {
      const user = JSON.parse(localStorage.getItem('cp_user'))
      localStorage.setItem('cp_user', JSON.stringify({ ...user, role: 'hr' }))
    })
    await page.reload()
    await page.getByRole('link', { name: 'Сменить роль', exact: true }).waitFor()
    await page.locator('.appnav-burger').waitFor()
    assert.equal(await page.locator('.dashboard-workspace').count(), 0)
    assert.deepEqual(errors, [])
    console.log('PASS: block result, tour, consultation form, cookie settings, logout cancellation, HR placeholder navigation')
    console.log('PASS: desktop sidebar, mobile menu/profile navigation, Escape, scroll lock, no page errors')
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })
