const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const fs = require('fs')
const path = require('path')
const base = 'http://127.0.0.1:5174/career-pulse/'
const out = path.resolve('design-preview/motion')
;(async () => {
  fs.mkdirSync(out, { recursive: true })
  const browser = await chromium.launch({ headless: true, channel: 'msedge' })
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
  const checks = {}, errors = []
  page.on('pageerror', error => errors.push(error.message))
  const scroll = async y => { await page.evaluate(y => window.scrollTo({ top: y, behavior: 'instant' }), y); await page.waitForTimeout(120) }
  const settle = async () => { await page.locator('.site-header nav').waitFor(); await page.waitForTimeout(300) }
  await page.goto(base)
  await settle()
  checks.initialTop = await page.evaluate(() => window.scrollY === 0)
  checks.initialHelperHidden = !(await page.locator('.bird-helper').isVisible())
  await scroll(300)
  checks.helperBelowThresholdHidden = !(await page.locator('.bird-helper').isVisible())
  await scroll(380)
  await page.waitForTimeout(500)
  checks.helperAfterScroll = await page.locator('.bird-helper').isVisible()
  await scroll(0)
  await page.waitForTimeout(400)
  checks.helperHidesAtTop = !(await page.locator('.bird-helper').isVisible())
  checks.levitation = await page.locator('.lv-scene').evaluate(el => {
    const style = getComputedStyle(el)
    return style.animationName === 'heroLevitate' && style.animationDuration === '5.2s'
  })
  await scroll(1400)
  await page.reload()
  await settle()
  checks.reloadTop = await page.evaluate(() => window.scrollY === 0)
  checks.reloadHelperHidden = !(await page.locator('.bird-helper').isVisible())
  await scroll(1400)
  await page.getByRole('link', { name: 'Материалы', exact: true }).click()
  await page.waitForURL(base + 'professions')
  await page.locator('.cat-card').first().waitFor()
  await settle()
  checks.newRouteTop = await page.evaluate(() => window.scrollY === 0)
  await scroll(730)
  await page.goBack()
  await page.waitForURL(base)
  await settle()
  checks.backRestores = await page.evaluate(() => Math.abs(window.scrollY - 1400) < 3)
  await page.goForward()
  await page.waitForURL(base + 'professions')
  await settle()
  checks.forwardRestores = await page.evaluate(() => Math.abs(window.scrollY - 730) < 3)
  await page.getByRole('link', { name: 'Диагностика', exact: true }).click()
  await page.waitForURL(base + '#how')
  await settle()
  checks.anchorVisible = await page.evaluate(() => {
    const top = document.getElementById('how').getBoundingClientRect().top
    return top >= document.querySelector('.site-header nav').getBoundingClientRect().bottom && top < 260
  })
  await page.goto(base + '#professions')
  await settle()
  checks.directHash = await page.evaluate(() => {
    const top = document.getElementById('professions').getBoundingClientRect().top
    return top >= 80 && top < 260
  })
  await page.goto(base)
  await settle()
  await page.evaluate(() => window.scrollTo({ top: document.getElementById('professions').offsetTop - 350, behavior: 'instant' }))
  await page.waitForTimeout(100)
  checks.revealRuns = await page.locator('.lv-prof-card').first().evaluate(el => el.getAnimations().length > 0)
  await page.waitForTimeout(1000)
  checks.revealRemainsVisible = await page.locator('.lv-prof-card').first().evaluate(el => getComputedStyle(el).opacity === '1' && el.getAnimations().length === 0)
  await page.screenshot({ path: path.join(out, 'scroll-reveal-desktop.png') })
  for (const width of [1440, 820, 390, 320]) {
    await page.setViewportSize({ width, height: 844 })
    await page.goto(base)
    await settle()
    checks['width' + width] = await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth && scrollY === 0)
    await scroll(380)
    await page.waitForTimeout(500)
    checks['helper' + width] = await page.locator('.bird-helper').evaluate(el => {
      const r = el.getBoundingClientRect()
      return r.left >= 0 && r.right <= innerWidth && r.bottom < innerHeight
    })
    if (width === 390) await page.screenshot({ path: path.join(out, 'scroll-helper-mobile.png') })
  }
  const reduced = await browser.newPage({ reducedMotion: 'reduce' })
  await reduced.goto(base)
  await reduced.locator('.lv-scene').waitFor()
  checks.reducedMotion = await reduced.locator('.lv-scene').evaluate(el => getComputedStyle(el).animationName === 'none')
  await reduced.evaluate(() => document.getElementById('professions').scrollIntoView({ behavior: 'instant' }))
  await reduced.waitForTimeout(150)
  checks.reducedReveal = await reduced.locator('.lv-prof-card').first().evaluate(el => el.getAnimations().length === 0 && getComputedStyle(el).opacity === '1')
  const fallback = await browser.newPage()
  await fallback.addInitScript(() => { window.IntersectionObserver = undefined })
  await fallback.goto(base)
  await fallback.locator('.lv-prof-card').first().waitFor()
  checks.observerFallback = await fallback.locator('.reveal').evaluateAll(els => els.every(el => getComputedStyle(el).opacity === '1'))
  fs.writeFileSync(path.join(out, 'report.json'), JSON.stringify({ checks, errors }, null, 2))
  console.log(JSON.stringify({ checks, errors }, null, 2))
  await browser.close()
  if (errors.length || Object.values(checks).some(v => !v)) process.exitCode = 1
})().catch(error => { console.error(error); process.exit(1) })
