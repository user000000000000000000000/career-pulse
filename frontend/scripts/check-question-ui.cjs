const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const assert = require('node:assert/strict')
const base = 'http://127.0.0.1:5174/career-pulse/'
;(async () => {
  const browser = await chromium.launch({ channel: 'chrome', headless: true })
  try {
    for (const width of [1440, 820, 390, 320]) {
      const page = await browser.newPage({ viewport: { width, height: 900 } })
      await page.goto(base + 'test/4')
      await page.getByRole('button', { name: 'Начать заново', exact: true }).click()
      const content = page.locator('.question-stage__content:not(.question-stage__ghost)')
      await content.waitFor()
      assert.equal(await content.locator('.qnav-back').isDisabled(), true)
      assert.equal(await content.locator('.qnav-finish').count(), 0)
      await content.locator('.scale-btn').nth(2).press('Enter')
      await page.waitForFunction(() => document.querySelector('.question-stage__content:not(.question-stage__ghost) .q-counter')?.textContent.trim().startsWith('2'))
      await page.waitForTimeout(400)
      assert.equal(await page.locator('.question-stage__ghost').count(), 0)
      await content.locator('.qnav-back').click()
      await page.waitForTimeout(400)
      const selected = content.locator('.scale-btn[aria-pressed="true"]')
      assert.equal(await selected.innerText(), '3')
      assert.ok((await selected.evaluate(el => getComputedStyle(el, '::after').content)).includes('✓'))
      const target = page.locator('.question-stage')
      const style = await selected.evaluate(el => ({ width: el.getBoundingClientRect().width, height: el.getBoundingClientRect().height }))
      assert.ok(style.width >= 44 && style.height >= 44, 'Touch area at ' + width)
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
      assert.ok(await target.evaluate(el => el.getBoundingClientRect().top >= document.querySelector('.cp-diag .topbar').getBoundingClientRect().bottom))
      await page.screenshot({ path: `design-preview/question-selection-${width}.png` })
      await page.reload()
      await content.locator('.scale-btn[aria-pressed="true"]').waitFor()
      assert.equal(await content.locator('.scale-btn[aria-pressed="true"]').innerText(), '3', 'Draft survives reload')
      await page.emulateMedia({ reducedMotion: 'reduce' })
      await content.getByRole('button', { name: /^Вопрос 2(?:,|$)/ }).click()
      await page.waitForTimeout(100)
      assert.equal(await content.evaluate(el => el.getAnimations().length), 0)
      assert.equal(await page.locator('.question-stage__ghost').count(), 0)
      console.log('PASS', width, 'selection marker, touch size, keyboard, back, draft, scrolling, reduced motion')
      await page.close()
    }
    const page = await browser.newPage({ viewport: { width: 390, height: 844 } })
    await page.goto(base + 'test/10')
    await page.getByRole('button', { name: 'Начать заново', exact: true }).click()
    const content = page.locator('.question-stage__content:not(.question-stage__ghost)')
    const text = content.locator('textarea')
    await text.scrollIntoViewIfNeeded()
    await page.waitForTimeout(300)
    const top = await page.evaluate(() => scrollY)
    await text.fill('Проверка сохранения текста и стабильности интерфейса.')
    await page.waitForTimeout(100)
    assert.equal(await page.evaluate(() => scrollY), top, 'Typing does not scroll')
    assert.equal(await page.locator('.question-stage__ghost').count(), 0, 'Typing does not animate the question')
    assert.equal(await content.evaluate(el => el.getAnimations().length), 0)
    await content.locator('.nav-row .btn-gold').click()
    await page.waitForTimeout(400)
    await content.locator('.nav-row .btn-ghost').click()
    await page.waitForTimeout(400)
    assert.equal(await text.inputValue(), 'Проверка сохранения текста и стабильности интерфейса.')
    console.log('PASS: open-text answer, typing stability and back/forward persistence')
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })
