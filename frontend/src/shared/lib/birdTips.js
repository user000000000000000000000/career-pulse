/** A session-local shuffled bag. No storage, user data or inferred results. */
export function takeBirdTip(pathname, session) {
  const key = pathname.split('/')[1] || 'home'
  const contextual = CONTEXT[key] || []
  const recent = session.recent || []
  session.bags ||= new Map()
  let bag = session.bags.get(key)
  if (!bag?.length) {
    bag = [...contextual, ...GENERAL].filter(tip => !recent.includes(tip))
    for (let i = bag.length - 1; i > 0; i--) {
      const j = Math.floor(Math.random() * (i + 1))
      ;[bag[i], bag[j]] = [bag[j], bag[i]]
    }
    session.bags.set(key, bag)
  }
  // On entering a section, lead with a relevant hint when one is available.
  const contextualIndex = session.lastSection !== key ? bag.findIndex(tip => contextual.includes(tip) && !recent.includes(tip)) : -1
  const index = contextualIndex >= 0 ? contextualIndex : bag.findIndex(tip => !recent.includes(tip))
  // At least 20 general hints keep a twelve-message gap possible across routes.
  const tip = index >= 0 ? bag.splice(index, 1)[0] : GENERAL.find(tip => !recent.includes(tip))
  session.lastSection = key
  session.recent = [...recent, tip].slice(-12)
  return tip
}
