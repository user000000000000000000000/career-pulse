export function getMascotBlockLine(num) {
  return MASCOT_BLOCK_LINES[num] || 'Продолжаем — ты молодец.'
}

export function getMascotHappyLine(seed = 0) {
  return MASCOT_HAPPY_LINES[seed % MASCOT_HAPPY_LINES.length]
}
