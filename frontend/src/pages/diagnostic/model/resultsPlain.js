export function buildCognitivePortrait(cogSorted) {
  if (!cogSorted?.length) return ''
  const [topKey] = cogSorted[0]
  const hook = COGNITIVE_PLAIN[topKey]?.hook
  if (!hook) return ''
  return `Тебе легче всего думать и учиться так: ${hook}.`
}

