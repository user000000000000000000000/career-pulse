// Отфильтрованные и персонализированные этапы под класс и выбранные профессии.
// Возвращает [{ id, horizon, title, desc, tasks: [string] }].
export function buildStages(ctx, chosen) {
  const g = gradeNum(ctx)
  const profs = (chosen || []).filter(Boolean).join(' и ') || 'выбранную профессию'
  return STAGES.filter(s => s.showFor(g)).map(s => ({
    id: s.id, horizon: s.horizon, title: s.title, desc: s.desc, tasks: s.tasks(profs),
  }))
}
