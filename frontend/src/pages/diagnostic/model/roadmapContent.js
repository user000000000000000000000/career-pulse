// Номер класса из анкеты (7–11), иначе null (студент/взрослый/не указан).
export function gradeNum(ctx = {}) {
  const m = String(ctx.grade || '').match(/\d+/)
  const n = m ? parseInt(m[0], 10) : null
  return (n && n >= 7 && n <= 11) ? n : null
}

