/** Сгруппировать вопросы по блокам (в порядке BLOCKS). */
export function questionsByBlock(blocks) {
  const out = {}
  for (const b of blocks) out[b.id] = []
  for (const q of QUESTION_BANK) {
    if (!out[q.block]) out[q.block] = []
    out[q.block].push(q)
  }
  return out
}

