const esc = v => `'${String(v).replace(/'/g, "''")}'`
const lines = [
  '-- Сопоставление профессия атласа → специальность, для всех 150 профессий (кроме 2 явно пропущенных).',
  '-- Сгенерировано generate-profession-specialty-map.mjs. Специальность должна уже существовать в specialties',
  '-- (см. specialties_bachelor.sql / magistratura_raw.sql / specialitet_raw.sql / specialties_college.sql).',
]
let total = 0
for (const [profId, entries] of MAP) {
  for (const [code, relevance] of entries) {
    lines.push(
      `insert into public.profession_specialty_map (profession_id, specialty_code, relevance) ` +
      `values (${profId}, ${esc(code)}, ${esc(relevance)}) ` +
      `on conflict (profession_id, specialty_code) do update set relevance = excluded.relevance;`
    )
    total++
  }
}
writeFileSync(new URL('./output/profession_specialty_map.sql', import.meta.url), lines.join('\n'), 'utf-8')
console.log(`Готово: ${MAP.length} профессий замаплено, ${total} строк insert.`)
